-- 0009_holder_snils_identity.sql — различение физлиц без хранения ФИО.
--
-- ЧТО БЫЛО НЕ ТАК. Физлицо в выписке приходит с ФИО, СНИЛС и паспортом.
-- Парсер их НЕ сохраняет (правило проекта: персональные данные в БД не
-- попадают), и правообладатель-физлицо оставался вообще без различителя:
-- `subject_uuid` считался как uuid5 от строки «unknown_individual», то есть
-- ОДИНАКОВЫЙ у всех. Две сестры с долями по 1/2 склеивались в одного субъекта,
-- и выписка на здание показывала одного собственника вместо двух.
--
-- РЕШЕНИЕ. Хранить не СНИЛС, а его производные:
--   `snils_hash`   — sha256 от одних цифр, первые 16 hex. Различитель: у двух
--                    разных людей он разный, у одного человека в разных
--                    выписках — один и тот же. Восстановить СНИЛС из него
--                    нельзя (перебор 11 цифр возможен, поэтому хеш и не
--                    выдаётся наружу как «анонимный» — он ключ, а не маска).
--   `snils_masked` — то, что показывают человеку: второй и предпоследний знак
--                    заменены на «*». Этого достаточно, чтобы не перепутать
--                    двух совладельцев в отчёте, и мало, чтобы опознать
--                    человека по одной этой строке.
-- ФИО, дата и место рождения, гражданство и паспорт не сохраняются нигде.

ALTER TABLE right_holders ADD COLUMN snils_masked TEXT;
ALTER TABLE right_holders ADD COLUMN snils_hash   TEXT;

CREATE INDEX IF NOT EXISTS idx_right_holders_snils_hash
    ON right_holders(snils_hash);
